import { useEffect, useState } from "react";
import { Loader2 } from "lucide-react";

import { useFormDirty } from "@/hooks/useFormDirty";

import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";

import type { Role, CreateRoleRequest, UpdateRoleRequest } from "./role.types";

type RoleFormProps = {
  role?: Role | null;
  saving: boolean;
  onSubmit: (data: CreateRoleRequest | UpdateRoleRequest) => void;
  onCancel: () => void;
};

type FormErrors = {
  roleName?: string;
  departmentCategory?: string;
  description?: string;
};

export function RoleForm({ role, saving, onSubmit, onCancel }: RoleFormProps) {
  const isEditMode = Boolean(role);

  const [roleName, setRoleName] = useState("");
  const [departmentCategory, setDepartmentCategory] = useState("");
  const [description, setDescription] = useState("");
  const [errors, setErrors] = useState<FormErrors>({});

  const initialFormData = {
    roleName: role?.roleName ?? "",
    departmentCategory: role?.departmentCategory ?? "",
    description: role?.description ?? "",
  };

  const currentFormData = {
    roleName,
    departmentCategory,
    description,
  };

  const isDirty = useFormDirty(initialFormData, currentFormData);

  useEffect(() => {
    setRoleName(role?.roleName ?? "");
    setDepartmentCategory(role?.departmentCategory ?? "");
    setDescription(role?.description ?? "");
    setErrors({});
  }, [role]);

  const validateForm = (): boolean => {
    const newErrors: FormErrors = {};
    const trimmedRoleName = roleName.trim();
    const trimmedCategory = departmentCategory.trim();
    const trimmedDescription = description.trim();

    if (!trimmedRoleName) {
      newErrors.roleName = "Role name is required.";
    } else if (trimmedRoleName.length < 2) {
      newErrors.roleName = "Role name must be at least 2 characters.";
    } else if (trimmedRoleName.length > 150) {
      newErrors.roleName = "Role name cannot exceed 150 characters.";
    }

    if (!trimmedCategory) {
      newErrors.departmentCategory = "Department category is required.";
    } else if (trimmedCategory.length < 2) {
      newErrors.departmentCategory = "Department category must be at least 2 characters.";
    } else if (trimmedCategory.length > 100) {
      newErrors.departmentCategory = "Department category cannot exceed 100 characters.";
    }

    if (trimmedDescription.length > 500) {
      newErrors.description = "Description cannot exceed 500 characters.";
    }

    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  const handleSubmit = (event: React.FormEvent<HTMLFormElement>) => {
    event.preventDefault();

    if (saving || !isDirty || !validateForm()) {
      return;
    }

    const data = {
      roleName: roleName.trim(),
      departmentCategory: departmentCategory.trim(),
      description: description.trim() || null,
    };

    onSubmit(data);
  };

  return (
    <form onSubmit={handleSubmit} className="space-y-6" noValidate>
      <div className="grid grid-cols-1 gap-5">
        {isEditMode && role && (
          <div className="space-y-2">
            <label htmlFor="roleId" className="text-sm font-medium">
              Role ID
            </label>
            <Input id="roleId" value={role.roleId} disabled />
            <p className="text-xs text-muted-foreground">
              Role ID is generated by the server and cannot be edited.
            </p>
          </div>
        )}

        <div className="space-y-2">
          <label htmlFor="roleName" className="text-sm font-medium">
            Role Name <span className="text-destructive">*</span>
          </label>
          <Input
            id="roleName"
            value={roleName}
            onChange={(event) => setRoleName(event.target.value)}
            placeholder="Enter role name"
            maxLength={150}
            disabled={saving}
            aria-invalid={Boolean(errors.roleName)}
          />
          {errors.roleName && <p className="text-sm text-destructive">{errors.roleName}</p>}
        </div>

        <div className="space-y-2">
          <label htmlFor="departmentCategory" className="text-sm font-medium">
            Department Category <span className="text-destructive">*</span>
          </label>
          <Input
            id="departmentCategory"
            value={departmentCategory}
            onChange={(event) => setDepartmentCategory(event.target.value)}
            placeholder="Enter department category"
            maxLength={100}
            disabled={saving}
            aria-invalid={Boolean(errors.departmentCategory)}
          />
          {errors.departmentCategory && (
            <p className="text-sm text-destructive">{errors.departmentCategory}</p>
          )}
        </div>

        <div className="space-y-2">
          <label htmlFor="roleDescription" className="text-sm font-medium">
            Description
          </label>
          <Textarea
            id="roleDescription"
            value={description}
            onChange={(event) => setDescription(event.target.value)}
            placeholder="Enter role description (optional)"
            rows={4}
            maxLength={500}
            disabled={saving}
          />
          <div className="flex justify-end">
            <span className="text-xs text-muted-foreground">{description.length}/500</span>
          </div>
          {errors.description && <p className="text-sm text-destructive">{errors.description}</p>}
        </div>
      </div>

      <div className="flex items-center justify-end gap-3 border-t pt-5">
        <Button type="button" variant="outline" onClick={onCancel} disabled={saving}>
          Cancel
        </Button>

        <Button type="submit" disabled={saving || !isDirty}>
          {saving && <Loader2 className="mr-2 h-4 w-4 animate-spin" />}
          {isEditMode ? "Update Role" : "Save Role"}
        </Button>
      </div>
    </form>
  );
}
